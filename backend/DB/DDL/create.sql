-- Social Media System - DDL - Create Table

CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_NAME VARCHAR2(50) NOT NULL, 
    PHONE VARCHAR2(20) NOT NULL,
    PHONE_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL,
    EMAIL_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    COVER_IMAGE VARCHAR2(500),
    BIOGRAPHY VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_USERS PRIMARY KEY (USER_ID),

    CONSTRAINT UK_USERS_PHONE UNIQUE (PHONE),

    CONSTRAINT UK_USERS_EMAIL UNIQUE (EMAIL),

    CONSTRAINT CK_USERS_PHONE_VERIFIED 
        CHECK (PHONE_VERIFIED IN (0, 1)),

    CONSTRAINT CK_USERS_EMAIL_VERIFIED 
        CHECK (EMAIL_VERIFIED IN (0, 1))
);

CREATE TABLE POSTS (
    POST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    CONTENT VARCHAR2(2000) NOT NULL, 
    IMAGE VARCHAR2(500),
    CREATE_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_POSTS PRIMARY KEY (POST_ID),

    CONSTRAINT FK_POSTS_USERS 
        FOREIGN KEY (USER_ID) 
        REFERENCES USERS(USER_ID)   
);

CREATE TABLE COMMENTS (
    COMMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    POST_ID NUMBER NOT NULL,
    CONTENT VARCHAR2(1000) NOT NULL, 
    CREATE_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_COMMENTS PRIMARY KEY (COMMENT_ID),

    CONSTRAINT FK_COMMENTS_USERS 
        FOREIGN KEY (USER_ID) 
        REFERENCES USERS(USER_ID),

    CONSTRAINT FK_COMMENTS_POSTS 
        FOREIGN KEY (POST_ID) 
        REFERENCES POSTS(POST_ID)
);

CREATE TABLE VERIFICATION_CODES (
    VERIFICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    PURPOSE VARCHAR2(20) NOT NULL,
    CODE_HASH VARCHAR2(255) NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    USED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_VERIFICATION_CODES PRIMARY KEY (VERIFICATION_ID),

    CONSTRAINT FK_VERIFICATION_USERS
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID),

    CONSTRAINT CK_VERIFICATION_PURPOSE
        CHECK (PURPOSE IN ('REGISTER', 'LOGIN'))
);

CREATE TABLE PASSWORD_RESET_TOKENS (
    RESET_TOKEN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID NUMBER NOT NULL,
    TOKEN_HASH VARCHAR2(255) NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    USED_AT TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_PASSWORD_RESET_TOKENS
        PRIMARY KEY (RESET_TOKEN_ID),

    CONSTRAINT FK_PASSWORD_RESET_USERS
        FOREIGN KEY (USER_ID)
        REFERENCES USERS(USER_ID)
);